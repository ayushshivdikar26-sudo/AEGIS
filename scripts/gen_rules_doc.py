#!/usr/bin/env python3
"""
Generate docs/RULES.md from data/permission_knowledge.json and data/scoring_config.json.
Ensures 100% transparency with zero hidden logic (FR-E6).
"""

import json
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent
KNOWLEDGE_PATH = BASE_DIR / "Backend" / "data" / "permission_knowledge.json"
CONFIG_PATH = BASE_DIR / "Backend" / "data" / "scoring_config.json"
OUTPUT_PATH = BASE_DIR / "docs" / "RULES.md"


def generate_rules_markdown() -> str:
    with open(KNOWLEDGE_PATH, encoding="utf-8") as f:
        kb = json.load(f)

    with open(CONFIG_PATH, encoding="utf-8") as f:
        cfg = json.load(f)

    lines: list[str] = []
    lines.append("# AEGIS Permission & Scoring Rules Catalogue")
    lines.append("")
    lines.append(
        f"> Auto-generated from `Backend/data/permission_knowledge.json` (Knowledge v{kb.get('knowledge_version')})"
    )
    lines.append(f"> and `Backend/data/scoring_config.json` (Formula v{cfg.get('formula_version')}).")
    lines.append("> Do not edit this file directly. Regenerate using `python scripts/gen_rules_doc.py`.")
    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("## 1. Risk Levels & Thresholds")
    lines.append("")
    lines.append("| Level | Score Range | Description |")
    lines.append("|---|---|---|")
    low_max = cfg["thresholds"]["low_max"]
    mid_max = cfg["thresholds"]["mid_max"]
    lines.append(f"| **Low** | 0 – {low_max} | Minimal or narrowly scoped permission exposure |")
    lines.append(f"| **Medium** | {low_max + 1} – {mid_max} | Moderate exposure; standard functional capabilities |")
    lines.append(f"| **High** | {mid_max + 1} – 100 | Significant capability exposure or sensitive system access |")
    lines.append("")
    lines.append("### Danger Floors")
    lines.append(
        f"- **Critical Floor ({cfg['floors']['critical_floor']}):** Applied when any weight-5 capability is requested."
    )
    lines.append(
        f"- **High Floor ({cfg['floors']['high_floor']}):** Applied when any weight-4 capability is requested (and no weight-5 is present)."
    )
    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("## 2. Host Pattern Scope Tiers")
    lines.append("")
    lines.append("| Tier | Weight | Risk Label | Description |")
    lines.append("|---|---|---|---|")
    tier_weights = cfg["host_tier_weights"]
    for tier, data in kb.get("host_tiers", {}).items():
        w = tier_weights.get(tier, cfg["default_unknown_weight"])
        lbl = cfg["weight_labels"].get(str(w), "medium")
        desc = data.get("allows", "")
        lines.append(f"| `{tier}` | {w} | {lbl.upper()} | {desc} |")
    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("## 3. WebExtension API Permissions Knowledge Base")
    lines.append("")
    lines.append("| Permission | Weight | Risk Label | Capabilities Allowed | Legitimate Use | Source | Reviewed |")
    lines.append("|---|---|---|---|---|---|---|")

    api_perms = kb.get("api_permissions", {})
    # Sort by weight descending, then name ascending
    sorted_api = sorted(api_perms.items(), key=lambda kv: (-kv[1].get("weight", 3), kv[0]))

    for name, data in sorted_api:
        w = data.get("weight", cfg["default_unknown_weight"])
        lbl = cfg["weight_labels"].get(str(w), "medium")
        allows = data.get("allows", "").replace("|", "\\|")
        legitimate = data.get("legitimate_use", "").replace("|", "\\|")
        source = data.get("source", "")
        source_link = f"[Docs]({source})" if source else "None"
        reviewed = "Yes" if data.get("reviewed") else "No"
        lines.append(f"| `{name}` | {w} | {lbl.upper()} | {allows} | {legitimate} | {source_link} | {reviewed} |")

    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("## 4. Permission Creep Assessment Rules")
    lines.append("")
    lines.append(f"- **Delta Review Threshold:** {cfg['creep']['delta_review']} points")
    lines.append(f"- **Delta Significant Threshold:** {cfg['creep']['delta_significant']} points")
    lines.append("")
    lines.append("### Creep Outcome Classifications")
    lines.append("1. **Significant increase in assessed permission exposure:**")
    lines.append("   - Score delta >= 15 points, OR")
    lines.append("   - Any added capability has weight 5, OR")
    lines.append("   - Host pattern broadened to a weight-5 tier (`all_sites`), OR")
    lines.append("   - Risk score crossed threshold into High level (> 69).")
    lines.append("2. **Permission changes require review:**")
    lines.append("   - Score delta >= 5 points, OR")
    lines.append("   - Any added capability has weight >= 3, OR")
    lines.append("   - Host pattern broadened to a wider tier, OR")
    lines.append("   - Any unrecognized capability added.")
    lines.append("3. **No significant permission creep detected:**")
    lines.append("   - All other changes (removals, or low-weight additions with delta < 5).")
    lines.append("")
    return "\n".join(lines) + "\n"


def main() -> None:
    content = generate_rules_markdown()
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    with open(OUTPUT_PATH, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"Generated {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
